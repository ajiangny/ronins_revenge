// Generates sound effects with ElevenLabs Sound Effects into Assets/Audio/Sfx (two takes each, `Name.mp3` and
// `Name_2.mp3`), where Ninja/Apply Audio picks them up. Run with `npm run sfx` (all) or `npm run sfx -- BossHit`.
// The SDK reads ELEVENLABS_API_KEY, which the npm script loads from .env.local.
import { ElevenLabsClient } from "@elevenlabs/elevenlabs-js";
import { createWriteStream } from "fs";
import { mkdir } from "fs/promises";
import { Readable } from "stream";
import { pipeline } from "stream/promises";

const OUT_DIR = new URL("../Assets/Audio/Sfx/", import.meta.url);

// Only the sounds made by this script; the original set was generated by hand in the ElevenLabs app.
const SOUNDS = {
  ParryClang: {
    seconds: 0.8,
    prompt:
      "A perfect katana parry: a bright, sharp steel-on-steel clang with a ringing metallic shimmer and a crackle " +
      "of sparks, punchy and satisfying, video game sound effect, no music.",
  },
  SamuraiCry: {
    seconds: 0.6,
    prompt:
      "A short male samurai death cry, a sharp pained grunt as he is cut down, clipped and punchy, close mic, " +
      "dry, no music, no reverb tail.",
  },
  PlayerHurt: {
    seconds: 0.5,
    prompt:
      "A young male ninja taking a hit: a short sharp pained grunt through gritted teeth, close mic, dry, " +
      "video game hurt sound, no music.",
  },
  BossHit: {
    seconds: 0.6,
    prompt:
      "A heavy katana slash landing on an armoured warrior: a meaty cut with a dull lacquered-armour thud and a " +
      "short metallic scrape, punchy fighting game impact, no music.",
  },
  BossStagger: {
    seconds: 1.5,
    prompt:
      "A boss's guard being broken in a fighting game: a huge metallic clang as her sword is knocked away, a " +
      "deep resonant ringing like a struck temple bell, and a whoosh of a stumble. Dramatic, no music.",
  },
};

const client = new ElevenLabsClient();
const wanted = process.argv.slice(2);
const names = wanted.length > 0 ? wanted : Object.keys(SOUNDS);

await mkdir(OUT_DIR, { recursive: true });
for (const name of names) {
  const sound = SOUNDS[name];
  if (!sound) {
    console.error(`Unknown sound "${name}". Known: ${Object.keys(SOUNDS).join(", ")}`);
    process.exitCode = 1;
    continue;
  }

  for (const suffix of ["", "_2"]) {
    console.log(`Generating ${name}${suffix}...`);
    try {
      const audio = await client.textToSoundEffects.convert({
        text: sound.prompt,
        durationSeconds: sound.seconds,
        promptInfluence: 0.6,
      });
      const source = typeof audio.pipe === "function" ? audio : Readable.fromWeb(audio);
      const file = new URL(`${name}${suffix}.mp3`, OUT_DIR);
      await pipeline(source, createWriteStream(file));
      console.log(`Saved ${file.pathname}`);
    } catch (err) {
      console.error(`API error for ${name}${suffix}:`, err.message ?? err);
      process.exitCode = 1;
    }
  }
}

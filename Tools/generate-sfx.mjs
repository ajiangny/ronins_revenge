const client = new ElevenLabsClient();
const wanted = process.argv.slice(2);
const names = wanted.length > 0 ? wanted : Object.keys(SOUNDS);

await mkdir(OUT_DIR, { recursive: true });
for (const name of names) {
  const sound = SOUNDS[name];
  if (!sound) {
    console.error(`Unknown sound "${name}". Known: ${Object.keys(SOUNDS).join(", ")}`);
    process.exitCode = 1;
    continue;
  }

  for (const suffix of ["", "_2"]) {
    console.log(`Generating ${name}${suffix}...`);
    try {
      const audio = await client.textToSoundEffects.convert({
        text: sound.prompt,
        durationSeconds: sound.seconds,
        promptInfluence: 0.6,
      });
      const source = typeof audio.pipe === "function" ? audio : Readable.fromWeb(audio);
      const file = new URL(`${name}${suffix}.mp3`, OUT_DIR);
      await pipeline(source, createWriteStream(file));
      console.log(`Saved ${file.pathname}`);
    } catch (err) {
      console.error(`API error for ${name}${suffix}:`, err.message ?? err);
      process.exitCode = 1;
    }
  }
}

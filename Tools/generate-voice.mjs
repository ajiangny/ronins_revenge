const args = process.argv.slice(2);
const fxOnly = args.includes("--fx-only");
const wanted = args.filter((a) => a !== "--fx-only");
// A voice that hasn't been picked yet. Its lines can't be voiced, even by name.
const unpicked = (voice) => voice.startsWith("TODO");
// All of Oliver's conversations, including the lines in Oni's and the other souls' voices: a bare run leaves them out
// until his voice is picked, so they don't go in with half a conversation missing. Naming one still voices it.
const HELD_FOR_OLIVER = /^(Oliver_|Duo_(RedHotIron|Quenching|LightningRod|Rust)_|Benibana_Intro_Steel|(Akagane|Mizore|Hibiki|Asagi)_Jealous_Steel)/;
const held = (n) => unpicked(OLIVER) && HELD_FOR_OLIVER.test(n);
const names = wanted.length > 0 ? wanted : Object.keys(LINES).filter((n) => !held(n) && (!fxOnly || LINE_FX[n] || FX[LINES[n][0]]));
const client = fxOnly ? null : new ElevenLabsClient();

// Writes the clip from its raw take through the voice's filter.
function bake(raw, out, filter) {
  execFileSync("ffmpeg", ["-v", "error", "-y", "-i", raw, "-filter_complex", filter, "-c:a", "libmp3lame", "-b:a", "128k", out]);
}

await mkdir(OUT_DIR, { recursive: true });
await mkdir(RAW_DIR, { recursive: true });
for (const name of names) {
  const line = LINES[name];
  if (!line) {
    console.error(`Unknown line "${name}". Known: ${Object.keys(LINES).join(", ")}`);
    process.exitCode = 1;
    continue;
  }

  const [voice, text] = line;
  if (unpicked(voice)) {
    console.error(`Skipping ${name}: its voice isn't picked yet (${voice}).`);
    process.exitCode = 1;
    continue;
  }
  const filter = LINE_FX[name] ?? FX[voice];
  const file = new URL(`${name}.mp3`, OUT_DIR);
  const raw = new URL(`${name}.mp3`, RAW_DIR);
  try {
    if (fxOnly) {
      if (!filter) continue;
      // A clip voiced before baking existed is its own raw take.
      if (!existsSync(raw)) await copyFile(file, raw);
    } else {
      console.log(`Voicing ${name}...`);
      const audio = await client.textToSpeech.convert(voice, {
        text,
        modelId: "eleven_v3",
        outputFormat: "mp3_44100_128",
      });
      const source = typeof audio.pipe === "function" ? audio : Readable.fromWeb(audio);
      await pipeline(source, createWriteStream(filter ? raw : file));
    }
    if (filter) bake(raw.pathname, file.pathname, filter);
    console.log(`Saved ${file.pathname}${filter ? " (baked)" : ""}`);
  } catch (err) {
    console.error(`Error for ${name}:`, err.message ?? err);
    process.exitCode = 1;
  }
}
